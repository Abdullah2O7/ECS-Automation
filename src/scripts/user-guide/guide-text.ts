/**
 * The kind of control a field is, from its Umbraco editor; decides how a step tells the reader to fill it in. (A switch is
 * recognised on the screen too: some switches are stored as text.)
 */
export type FieldKind = 'text' | 'richText' | 'media' | 'toggle' | 'blocks' | 'picker' | 'choice' | 'date' | 'other';

const FIELD_KINDS: [RegExp, FieldKind][] = [
  [/textbox|textarea|plain\.string|email|integer|decimal/, 'text'],
  [/richtext|tinymce|markdown/, 'richText'],
  [/mediapicker|imagecropper|uploadfield/, 'media'],
  [/truefalse/, 'toggle'],
  [/blocklist|blockgrid/, 'blocks'],
  [/picker|multinodetree/, 'picker'],
  [/dropdown|checkboxlist|radiobutton|tags/, 'choice'],
  [/date/, 'date'],
];

export const fieldKindOf = (editorAlias: string): FieldKind => FIELD_KINDS.find(([pattern]) => pattern.test(editorAlias.toLowerCase()))?.[1] ?? 'other';

/** A field of a form as the steps describe it: its label and what the screen shows about it. */
export type FieldView = { label: string; description: string | null; required: boolean; kind: FieldKind; button?: string; state?: string };

